"""Retrieval and answer evals over evals/questions.json.

Retrieval metrics need no LLM. Document-level relevance: a question lists the documents that
together contain the answer (`gold_docs`); retrieved chunks map to their documents.
  recall@k       fraction of gold documents among the top-k chunks' documents
  full@k         share of questions where ALL gold documents are in the top-k
  mrr            reciprocal rank of the first gold document in the ranked chunk list
  fact@k         the gold fact string appears in the concatenated top-k chunk text
With --llm, each retriever's answer is generated by the flow:
  ctx_fact       the gold fact string appears in the context the answer step read (top-k + evidence)
  answer_fact    the answer contains every gold fact string (case-insensitive, strict)
  grounded       the flow's own groundedness check passed
With --judge as well, a second model (JUDGE_MODEL, a different family by default) grades each answer
against the gold facts and the context:
  answer_judge   correct = 1, partial = 0.5, incorrect = 0
  faithful       every claim in the answer is supported by the context
"""

import argparse
import json
import os
import re
import statistics
from pathlib import Path

from opsgraph import config
from opsgraph.flow import ask, build_flow
from opsgraph.llm import LLMClient
from opsgraph.retrieval import RETRIEVERS, Retriever, unique

QUESTIONS = config.EVAL_DIR / "questions.json"


def load_questions() -> list[dict]:
    return json.loads(QUESTIONS.read_text())


def norm(s: str) -> str:
    """Lower case, markdown emphasis and code marks removed, every kind of space folded to one."""
    s = re.sub(r"[*_`]", "", s.lower())
    return re.sub(r"[\s\u00a0\u202f\u2009\u200b]+", " ", s)


def score_question(q: dict, chunks: list, k: int) -> dict:
    top = chunks[:k]
    docs = {c.doc_id for c in top}
    gold = set(q["gold_docs"])
    ranked_docs = unique([c.doc_id for c in chunks])
    first = next((i for i, d in enumerate(ranked_docs, 1) if d in gold), None)
    ctx = norm(" ".join(c.text for c in top))
    return {
        "recall": len(gold & docs) / len(gold),
        "full": float(gold <= docs),
        "mrr": 1.0 / first if first else 0.0,
        "fact": float(all(norm(f) in ctx for f in q["facts"])),
    }


def aggregate(rows: list[dict]) -> dict:
    keys = ("recall", "full", "mrr", "fact", *ANSWER_KEYS)
    out = {"n": len(rows)}
    for key in keys:
        vals = [r[key] for r in rows if key in r]
        if vals:
            out[key] = round(statistics.mean(vals), 3)
    return out


def run_retrieval(k: int = 5, retriever: Retriever | None = None) -> dict:
    retriever = retriever or Retriever()
    questions = load_questions()
    results: dict = {}
    for name in RETRIEVERS:
        rows = []
        for q in questions:
            res = retriever.retrieve(q["question"], name, k)
            rows.append({"id": q["id"], "kind": q["kind"], **score_question(q, res.chunks, k)})
        results[name] = {
            "all": aggregate(rows),
            "single": aggregate([r for r in rows if r["kind"] == "single"]),
            "multi": aggregate([r for r in rows if r["kind"] == "multi"]),
            "rows": rows,
        }
    return results


JUDGE_PROMPT = (
    "You grade answers from an assistant for on-call engineers. You get the question, the key facts a "
    "correct answer must convey, the context the assistant read, and its answer. Return only a JSON object: "
    '{"correctness": "correct" | "partial" | "incorrect", "faithful": true | false}. '
    "correctness: 'correct' when the answer conveys every key fact (wording may differ) and contradicts none, "
    "'partial' when it conveys some, 'incorrect' otherwise. faithful: true when every claim in the answer is "
    "supported by the context. Judge only against the key facts and the context."
)


def parse_judge(raw: str) -> dict:
    """Reads the judge's JSON, tolerating <think> blocks and code fences."""
    raw = re.sub(r"<think>.*?</think>", "", raw, flags=re.S)
    start, end = raw.find("{"), raw.rfind("}")
    if start < 0 or end <= start:
        raise ValueError(f"judge reply has no JSON object: {raw[:200]}")
    obj = json.loads(raw[start : end + 1])
    label = str(obj.get("correctness", "")).lower()
    if label not in ("correct", "partial", "incorrect"):
        raise ValueError(f"unknown correctness label: {obj.get('correctness')!r}")
    return {
        "answer_judge": {"correct": 1.0, "partial": 0.5, "incorrect": 0.0}[label],
        "faithful": float(obj.get("faithful") in (True, "true")),
    }


def judge_answer(judge: LLMClient, question: str, facts: list[str], context: str, answer: str) -> dict:
    user = f"QUESTION:\n{question}\n\nKEY FACTS:\n" + "\n".join(f"- {f}" for f in facts)
    user += f"\n\nCONTEXT:\n{context}\n\nANSWER:\n{answer}"
    try:
        return parse_judge(judge.chat(JUDGE_PROMPT, user))
    except ValueError:
        return parse_judge(judge.chat(JUDGE_PROMPT, user + "\n\nReply with the JSON object only."))


ANSWER_KEYS = ("ctx_fact", "answer_fact", "grounded", "answer_judge", "faithful")


def run_answers(
    results: dict,
    k: int = 5,
    retriever: Retriever | None = None,
    retrievers: tuple[str, ...] = RETRIEVERS,
    judge: LLMClient | None = None,
) -> dict:
    """Add LLM answer-level scores (requires LLM_API_KEY)."""
    retriever = retriever or Retriever()
    flow = build_flow(retriever, LLMClient(), llm_check=False)  # lexical groundedness keeps the eval cheap
    questions = {q["id"]: q for q in load_questions()}
    for name in retrievers:
        for row in results[name]["rows"]:
            q = questions[row["id"]]
            out = ask(flow, q["question"], retriever=name, k=k)
            context = "\n\n".join(c.text for c in out["result"].chunks)
            row["ctx_fact"] = float(all(norm(f) in norm(context) for f in q["facts"]))
            row["answer_fact"] = float(all(norm(f) in norm(out["answer"]) for f in q["facts"]))
            row["grounded"] = float(out["grounded"])
            row["answer"] = out["answer"]
            if judge:
                row |= judge_answer(judge, q["question"], q["facts"], context, out["answer"])
        for part in ("all", "single", "multi"):
            sel = [r for r in results[name]["rows"] if part == "all" or r["kind"] == part]
            results[name][part] = aggregate(sel) | {
                key: round(statistics.mean(r[key] for r in sel), 3) for key in ANSWER_KEYS if key in sel[0]
            }
    return results


def markdown_report(results: dict, k: int, label: str, answers: bool) -> str:
    lines = [
        f"# Eval report ({label})",
        "",
        f"Sample data, fictional. k = {k} chunks. {len(load_questions())} labelled questions.",
        "",
    ]
    answer_cols = [key for key in ANSWER_KEYS if answers and any(key in results[n]["all"] for n in RETRIEVERS)]
    for part, title in (("all", "All questions"), ("single", "Single-hop"), ("multi", "Multi-hop")):
        cols = f"| Retriever | n | recall@{k} | full@{k} | MRR | fact@{k} |" + "".join(f" {c} |" for c in answer_cols)
        sep = "|---|---|---|---|---|---|" + "---|" * len(answer_cols)
        lines += [f"## {title}", "", cols, sep]
        for name in RETRIEVERS:
            a = results[name][part]
            row = f"| {name} | {a['n']} | {a['recall']:.3f} | {a['full']:.3f} | {a['mrr']:.3f} | {a['fact']:.3f} |"
            row += "".join(f" {a[c]:.3f} |" if c in a else " - |" for c in answer_cols)
            lines.append(row)
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--k", type=int, default=5)
    ap.add_argument("--llm", action="store_true", help="also run LLM answers (needs LLM_API_KEY)")
    ap.add_argument("--judge", action="store_true", help="with --llm: grade answers with JUDGE_MODEL")
    ap.add_argument("--retrievers", default=",".join(RETRIEVERS), help="comma list for the answer run")
    ap.add_argument("--label", default="rule-based extractor")
    ap.add_argument("--out", default="")
    args = ap.parse_args()
    results = run_retrieval(args.k)
    if args.llm:
        judge = LLMClient(model=os.getenv("JUDGE_MODEL", "qwen/qwen3.8-27b")) if args.judge else None
        names = tuple(n for n in args.retrievers.split(",") if n in RETRIEVERS)
        results = run_answers(results, args.k, retrievers=names, judge=judge)
    md = markdown_report(results, args.k, args.label, args.llm)
    print(md)
    if args.out:
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.with_suffix(".json").write_text(json.dumps(results, indent=1))
        out.write_text(md + "\n")


if __name__ == "__main__":
    main()
